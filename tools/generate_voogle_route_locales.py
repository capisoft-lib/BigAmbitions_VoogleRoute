def merged_locale(locale: str) -> dict[str, str]:
    base = dict(LOCALES[locale])
    extra = NEW_KEYS.get(locale, NEW_KEYS["en"])
    base.update(extra)
    return base


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    en_keys = list(merged_locale("en").keys())

    for locale in LOCALES:
        strings = merged_locale(locale)
        if list(strings.keys()) != en_keys:
            missing = set(en_keys) - set(strings)
            extra = set(strings) - set(en_keys)
            raise SystemExit(f"{locale}: key mismatch missing={missing} extra={extra}")

        path = OUT / f"{locale}.json"
        with path.open("w", encoding="utf-8", newline="\n") as f:
            json.dump(strings, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"wrote {path.name}")

    print(f"done: {len(LOCALES)} locales, {len(en_keys)} keys each")


if __name__ == "__main__":
    main()
